create or replace function public.validate_drrm_incident_barangay()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public
as $function$
begin
    if new.barangay_id is null then
        return new;
    end if;

    if not exists (
        select 1
        from public.barangays as barangay
        where barangay.barangay_id = new.barangay_id
          and barangay.boundary_dataset_version_id = 'b386cd54-2288-423f-9b92-2092333333c1'::uuid
          and barangay.record_status = 'INACTIVE'
          and barangay.name <> 'Barangay 176'
    ) then
        raise exception using errcode = '23514', message = 'The incident barangay reference is not in the validated Caloocan catalog.';
    end if;

    return new;
end;
$function$;

drop trigger if exists drrm_incidents_validate_barangay on public.drrm_incidents;
create trigger drrm_incidents_validate_barangay
before insert or update of barangay_id on public.drrm_incidents
for each row execute function public.validate_drrm_incident_barangay();

create or replace function public.transition_drrm_incident(
    p_incident_id uuid,
    p_action text,
    p_actor_reference text,
    p_notes text default null,
    p_assigned_department_reference text default null,
    p_assigned_user_reference text default null
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $function$
declare
    incident_record public.drrm_incidents%rowtype;
    target_status text;
    log_action_type text;
begin
    p_action := upper(btrim(coalesce(p_action, '')));
    p_actor_reference := btrim(coalesce(p_actor_reference, ''));
    p_notes := nullif(btrim(coalesce(p_notes, '')), '');
    p_assigned_department_reference := nullif(btrim(coalesce(p_assigned_department_reference, '')), '');
    p_assigned_user_reference := nullif(btrim(coalesce(p_assigned_user_reference, '')), '');

    if p_actor_reference = '' or char_length(p_actor_reference) > 200 then
        raise exception using errcode = '22023', message = 'A valid incident actor reference is required.';
    end if;
    if p_notes is not null and (char_length(p_notes) > 2000 or p_notes ~ '[<>]') then
        raise exception using errcode = '22023', message = 'The incident action note is invalid.';
    end if;
    if p_assigned_department_reference is not null
       and char_length(p_assigned_department_reference) > 200 then
        raise exception using errcode = '22023', message = 'The department reference is invalid.';
    end if;
    if p_assigned_user_reference is not null
       and char_length(p_assigned_user_reference) > 200 then
        raise exception using errcode = '22023', message = 'The user reference is invalid.';
    end if;

    select * into incident_record
    from public.drrm_incidents
    where id = p_incident_id
    for update;

    if not found then
        raise exception using errcode = 'P0002', message = 'The incident could not be found.';
    end if;

    case p_action
        when 'REVIEW' then
            if incident_record.status <> 'SUBMITTED' then
                raise exception using errcode = '23514', message = 'Only a submitted incident can enter review.';
            end if;
            target_status := 'UNDER_REVIEW';
            log_action_type := 'REVIEW_NOTE';
        when 'VERIFY' then
            if incident_record.status <> 'UNDER_REVIEW' then
                raise exception using errcode = '23514', message = 'Only an incident under review can be verified.';
            end if;
            target_status := 'VERIFIED';
            log_action_type := 'VERIFICATION_NOTE';
        when 'ASSIGN' then
            if incident_record.status <> 'VERIFIED' then
                raise exception using errcode = '23514', message = 'Only a verified incident can be assigned.';
            end if;
            if p_assigned_department_reference is null and p_assigned_user_reference is null then
                raise exception using errcode = '22023', message = 'A department or user assignment reference is required.';
            end if;
            target_status := 'ASSIGNED';
            log_action_type := 'ASSIGNMENT_NOTE';
        when 'RESOLVE' then
            if incident_record.status <> 'RESPONDING' then
                raise exception using errcode = '23514', message = 'Only an incident with an active response can be resolved.';
            end if;
            if p_notes is null then
                raise exception using errcode = '22023', message = 'A resolution note is required.';
            end if;
            target_status := 'RESOLVED';
            log_action_type := 'RESOLUTION_NOTE';
        when 'CLOSE' then
            if incident_record.status <> 'RESOLVED' then
                raise exception using errcode = '23514', message = 'Only a resolved incident can be closed.';
            end if;
            target_status := 'CLOSED';
            log_action_type := 'CLOSURE_NOTE';
        when 'REJECT' then
            if incident_record.status not in ('SUBMITTED', 'UNDER_REVIEW') then
                raise exception using errcode = '23514', message = 'This incident can no longer be rejected.';
            end if;
            if p_notes is null then
                raise exception using errcode = '22023', message = 'A rejection reason is required.';
            end if;
            target_status := 'REJECTED';
            log_action_type := 'REJECTION_NOTE';
        else
            raise exception using errcode = '22023', message = 'The incident lifecycle action is invalid.';
    end case;

    if p_action <> 'ASSIGN'
       and (p_assigned_department_reference is not null or p_assigned_user_reference is not null) then
        raise exception using errcode = '22023', message = 'Assignment references are only accepted for assignment actions.';
    end if;

    update public.drrm_incidents
    set status = target_status,
        verification_status = case
            when p_action = 'REVIEW' then 'IN_REVIEW'
            when p_action = 'VERIFY' then 'VERIFIED'
            when p_action = 'REJECT' then 'REJECTED'
            else verification_status
        end,
        verified_at = case when p_action = 'VERIFY' then now() else verified_at end,
        verified_by_reference = case when p_action = 'VERIFY' then p_actor_reference else verified_by_reference end,
        assigned_department_reference = case
            when p_action = 'ASSIGN' then p_assigned_department_reference
            else assigned_department_reference
        end,
        assigned_user_reference = case
            when p_action = 'ASSIGN' then p_assigned_user_reference
            else assigned_user_reference
        end,
        resolved_at = case when p_action = 'RESOLVE' then now() else resolved_at end,
        closed_at = case when p_action = 'CLOSE' then now() else closed_at end
    where id = p_incident_id
      and status = incident_record.status;

    if not found then
        raise exception using errcode = '40001', message = 'The incident changed before the action completed.';
    end if;

    insert into public.drrm_incident_status_history (
        incident_id, from_status, to_status, changed_by_reference, notes
    ) values (
        p_incident_id, incident_record.status, target_status, p_actor_reference, p_notes
    );

    if p_action = 'ASSIGN' then
        insert into public.drrm_incident_assignments (
            incident_id, department_reference, user_reference,
            assigned_by_reference, notes
        ) values (
            p_incident_id, p_assigned_department_reference,
            p_assigned_user_reference, p_actor_reference, p_notes
        );
    end if;

    if p_notes is not null then
        insert into public.drrm_incident_response_logs (
            incident_id, action_type, message, created_by_reference
        ) values (
            p_incident_id, log_action_type, p_notes, p_actor_reference
        );
    end if;

    return jsonb_build_object(
        'id', p_incident_id,
        'incident_number', incident_record.incident_number,
        'previous_status', incident_record.status,
        'status', target_status
    );
end;
$function$;

create or replace function public.add_drrm_incident_response(
    p_incident_id uuid,
    p_action_type text,
    p_message text,
    p_actor_reference text
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $function$
declare
    incident_record public.drrm_incidents%rowtype;
    final_status text;
begin
    p_action_type := upper(btrim(coalesce(p_action_type, '')));
    p_message := btrim(coalesce(p_message, ''));
    p_actor_reference := btrim(coalesce(p_actor_reference, ''));

    if p_action_type not in ('DISPATCH_NOTE', 'RESPONSE_UPDATE') then
        raise exception using errcode = '22023', message = 'The response action type is invalid.';
    end if;
    if p_message = '' or char_length(p_message) > 5000 or p_message ~ '[<>]' then
        raise exception using errcode = '22023', message = 'The response message is invalid.';
    end if;
    if p_actor_reference = '' or char_length(p_actor_reference) > 200 then
        raise exception using errcode = '22023', message = 'A valid incident actor reference is required.';
    end if;

    select * into incident_record
    from public.drrm_incidents
    where id = p_incident_id
    for update;

    if not found then
        raise exception using errcode = 'P0002', message = 'The incident could not be found.';
    end if;
    if incident_record.status not in ('ASSIGNED', 'RESPONDING') then
        raise exception using errcode = '23514', message = 'Response updates require an assigned or responding incident.';
    end if;
    if incident_record.status = 'ASSIGNED' and p_action_type <> 'DISPATCH_NOTE' then
        raise exception using errcode = '23514', message = 'The first response entry must be a dispatch note.';
    end if;

    final_status := incident_record.status;
    if incident_record.status = 'ASSIGNED' then
        update public.drrm_incidents
        set status = 'RESPONDING'
        where id = p_incident_id and status = 'ASSIGNED';

        if not found then
            raise exception using errcode = '40001', message = 'The incident changed before the response was recorded.';
        end if;

        insert into public.drrm_incident_status_history (
            incident_id, from_status, to_status, changed_by_reference, notes
        ) values (
            p_incident_id, 'ASSIGNED', 'RESPONDING', p_actor_reference, p_message
        );
        final_status := 'RESPONDING';
    end if;

    insert into public.drrm_incident_response_logs (
        incident_id, action_type, message, created_by_reference
    ) values (
        p_incident_id, p_action_type, p_message, p_actor_reference
    );

    return jsonb_build_object(
        'id', p_incident_id,
        'incident_number', incident_record.incident_number,
        'previous_status', incident_record.status,
        'status', final_status,
        'action_type', p_action_type
    );
end;
$function$;

