create or replace function public.verify_module3_incident_schema()
returns jsonb
language sql
stable
security definer
set search_path = pg_catalog, public
as $function$
    with target_tables as (
        select c.relname, c.relrowsecurity
        from pg_catalog.pg_class as c
        join pg_catalog.pg_namespace as n on n.oid = c.relnamespace
        where n.nspname = 'public'
          and c.relkind = 'r'
          and c.relname in (
              'drrm_incident_types', 'drrm_incident_severities',
              'drrm_incidents', 'drrm_incident_status_history',
              'drrm_incident_assignments', 'drrm_incident_response_logs'
          )
    ),
    target_roles as (
        select unnest(array['anon', 'authenticated']) as role_name
    ),
    target_table_names as (
        select unnest(array[
            'drrm_incident_types', 'drrm_incident_severities',
            'drrm_incidents', 'drrm_incident_status_history',
            'drrm_incident_assignments', 'drrm_incident_response_logs'
        ]) as table_name
    )
    select jsonb_build_object(
        'tables_exist', (select count(*) = 6 from target_tables),
        'rls_enabled', (select count(*) = 6 and bool_and(relrowsecurity) from target_tables),
        'direct_client_privileges_restricted', not exists (
            select 1
            from target_roles cross join target_table_names
            where has_table_privilege(
                target_roles.role_name,
                'public.' || target_table_names.table_name,
                'SELECT,INSERT,UPDATE,DELETE'
            )
        ),
        'policy_count', (
            select count(*)
            from pg_catalog.pg_policies
            where schemaname = 'public'
              and tablename in (select table_name from target_table_names)
        ),
        'incident_type_count', (select count(*) from public.drrm_incident_types),
        'incident_type_seed_valid', (
            select count(*) = 10
            from public.drrm_incident_types
            where code in (
                'FLOOD', 'FIRE', 'LANDSLIDE', 'EARTHQUAKE', 'ROAD_BLOCKAGE',
                'FALLEN_TREE', 'STRUCTURAL_DAMAGE', 'MEDICAL_EMERGENCY',
                'UTILITY_HAZARD', 'OTHER'
            ) and is_active
        ),
        'severity_count', (select count(*) from public.drrm_incident_severities),
        'severity_seed_valid', (
            select count(*) = 4
            from public.drrm_incident_severities
            where code in ('LOW', 'MODERATE', 'HIGH', 'CRITICAL') and is_active
        ),
        'incident_count', (select count(*) from public.drrm_incidents),
        'status_history_count', (select count(*) from public.drrm_incident_status_history),
        'assignment_count', (select count(*) from public.drrm_incident_assignments),
        'response_log_count', (select count(*) from public.drrm_incident_response_logs),
        'warning_trigger_count', (
            select count(*)
            from pg_catalog.pg_trigger as trigger_record
            join pg_catalog.pg_class as table_record on table_record.oid = trigger_record.tgrelid
            where table_record.relname = 'drrm_incidents'
              and pg_catalog.pg_get_triggerdef(trigger_record.oid) ilike '%early_warning%'
              and not trigger_record.tgisinternal
        )
    );
$function$;

revoke all on function public.verify_module3_incident_schema() from public, anon, authenticated;
grant execute on function public.verify_module3_incident_schema() to service_role;

notify pgrst, 'reload schema';

commit;
