create or replace function public.record_drrm_incident_submission()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public
as $function$
begin
    if new.status <> 'SUBMITTED'
       or new.verification_status <> 'PENDING'
       or new.verified_at is not null
       or new.verified_by_reference is not null
       or new.assigned_department_reference is not null
       or new.assigned_user_reference is not null
       or new.resolved_at is not null
       or new.closed_at is not null then
        raise exception using errcode = '23514', message = 'New incident records must enter through the submitted state.';
    end if;

    insert into public.drrm_incident_status_history (
        incident_id, from_status, to_status, changed_by_reference, notes
    ) values (
        new.id,
        null,
        'SUBMITTED',
        coalesce(new.created_by_reference, new.reporter_reference, 'SYSTEM:INGESTION'),
        null
    );
    return new;
end;
$function$;

