create table if not exists public.drrm_incident_types (
    incident_type_id smallint generated by default as identity primary key,
    code text not null,
    label text not null,
    sort_order smallint not null,
    is_active boolean not null default true,
    created_at timestamptz not null default now(),

    constraint drrm_incident_types_code_unique unique (code),
    constraint drrm_incident_types_sort_order_unique unique (sort_order),
    constraint drrm_incident_types_code_format check (
        code = upper(code) and code ~ '^[A-Z][A-Z0-9_]*$'
    ),
    constraint drrm_incident_types_label_required check (btrim(label) <> ''),
    constraint drrm_incident_types_sort_order_positive check (sort_order > 0)
);

create table if not exists public.drrm_incident_severities (
    severity_id smallint generated by default as identity primary key,
    code text not null,
    label text not null,
    severity_rank smallint not null,
    is_active boolean not null default true,
    created_at timestamptz not null default now(),

    constraint drrm_incident_severities_code_unique unique (code),
    constraint drrm_incident_severities_rank_unique unique (severity_rank),
    constraint drrm_incident_severities_code_check check (
        code in ('LOW', 'MODERATE', 'HIGH', 'CRITICAL')
    ),
    constraint drrm_incident_severities_label_required check (btrim(label) <> ''),
    constraint drrm_incident_severities_rank_check check (severity_rank between 1 and 4)
);

create sequence if not exists public.drrm_incident_number_seq
    as bigint
    start with 1
    increment by 1
    minvalue 1
    no maxvalue
    cache 20;

create or replace function public.next_drrm_incident_number()
returns text
language plpgsql
volatile
security definer
set search_path = pg_catalog, public
as $function$
declare
    sequence_value bigint;
begin
    sequence_value := nextval('public.drrm_incident_number_seq');
    return 'INC-' || to_char(current_date, 'YYYY') || '-' || lpad(sequence_value::text, 6, '0');
end;
$function$;

